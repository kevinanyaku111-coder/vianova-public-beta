import os, re, secrets, sqlite3
from pathlib import Path
from functools import wraps
from flask import Flask, request, redirect, url_for, session, flash, render_template, jsonify, send_from_directory, abort
from werkzeug.security import generate_password_hash, check_password_hash
from werkzeug.utils import secure_filename

app=Flask(__name__)
app.secret_key=os.environ.get('VIANOVA_SECRET_KEY') or secrets.token_hex(32)
app.config['MAX_CONTENT_LENGTH']=100*1024*1024
UPLOAD=os.environ.get('VIANOVA_UPLOAD_FOLDER',str(Path(__file__).parent/'static'/'uploads'))
Path(UPLOAD).mkdir(parents=True,exist_ok=True)
DBURL=os.environ.get('DATABASE_URL','').strip()

def connect():
    if DBURL:
        import psycopg
        from psycopg.rows import dict_row
        return psycopg.connect(DBURL.replace('postgres://','postgresql://',1),row_factory=dict_row)
    c=sqlite3.connect(str(Path(__file__).parent/'vianova.db')); c.row_factory=sqlite3.Row; return c

def qmark(s): return s.replace('?','%s') if DBURL else s

def query(sql,args=(),many=False,write=False):
    with connect() as c:
        cur=c.cursor(); cur.execute(qmark(sql),args)
        if write: c.commit(); return None
        return cur.fetchall() if many else cur.fetchone()

def init_db():
    schema=["""CREATE TABLE IF NOT EXISTS users(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(30) UNIQUE NOT NULL, email VARCHAR(254) UNIQUE NOT NULL, password_hash TEXT NOT NULL, bio VARCHAR(300) DEFAULT '', avatar TEXT DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""",
    """CREATE TABLE IF NOT EXISTS posts(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, caption TEXT NOT NULL, media TEXT DEFAULT '', media_type VARCHAR(10) DEFAULT 'text', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""",
    """CREATE TABLE IF NOT EXISTS likes(user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE, PRIMARY KEY(user_id,post_id))""",
    """CREATE TABLE IF NOT EXISTS comments(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE, body VARCHAR(500) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)"""]
    with connect() as c:
        cur=c.cursor()
        for s in schema: cur.execute(s)
        c.commit()

def me():
    if not session.get('uid'): return None
    return query('SELECT id,username,email,bio,avatar FROM users WHERE id=?',(session['uid'],))
def required(fn):
    @wraps(fn)
    def w(*a,**k):
        if not me(): flash('Please sign in first.'); return redirect(url_for('login'))
        return fn(*a,**k)
    return w
@app.context_processor
def ctx(): return {'current_user':me()}
def save_file(f,prefix,images_only=False):
    if not f or not f.filename:return ''
    name=secure_filename(f.filename); ext=Path(name).suffix.lower()
    allowed={'.jpg','.jpeg','.png','.webp'} if images_only else {'.jpg','.jpeg','.png','.webp','.mp4','.webm','.mov','.m4v'}
    if ext not in allowed: raise ValueError('Unsupported file type. Use a common image or MP4/WebM/MOV video.')
    out=f'{prefix}_{secrets.token_hex(12)}{ext}'; f.save(os.path.join(UPLOAD,out)); return out
@app.route('/')
def home(): return redirect(url_for('feed') if me() else url_for('welcome'))
@app.route('/welcome')
def welcome(): return render_template('welcome.html')
@app.route('/register',methods=['GET','POST'])
def register():
    if request.method=='POST':
        u=request.form.get('username','').strip().lstrip('@'); e=request.form.get('email','').strip().lower(); p=request.form.get('password','')
        if not re.fullmatch(r'[A-Za-z0-9_.]{3,30}',u): flash('Username must be 3–30 letters, numbers, dots or underscores.')
        elif not re.fullmatch(r'[^@\s]+@[^@\s]+\.[^@\s]+',e): flash('Enter a valid email address.')
        elif len(p)<8: flash('Password must be at least 8 characters.')
        else:
            try:
                query('INSERT INTO users(username,email,password_hash) VALUES(?,?,?)',(u,e,generate_password_hash(p)),write=True); flash('Account created. Sign in now.'); return redirect(url_for('login'))
            except Exception: flash('That username or email may already be registered.')
    return render_template('register.html')
@app.route('/login',methods=['GET','POST'])
def login():
    if request.method=='POST':
        e=request.form.get('email','').strip().lower(); u=query('SELECT id,password_hash FROM users WHERE email=?',(e,))
        if u and check_password_hash(u['password_hash'],request.form.get('password','')): session.clear(); session['uid']=u['id']; return redirect(url_for('feed'))
        flash('Email or password was incorrect.')
    return render_template('login.html')
@app.route('/logout',methods=['POST'])
def logout(): session.clear(); return redirect(url_for('welcome'))
@app.route('/feed')
@required
def feed():
    rows=query('SELECT posts.id,posts.user_id,posts.caption,posts.media,posts.media_type,posts.created_at,users.username,users.avatar FROM posts JOIN users ON users.id=posts.user_id ORDER BY posts.id DESC LIMIT 100',many=True); posts=[]
    for r in rows:
        p=dict(r); p['likes']=query('SELECT COUNT(*) AS n FROM likes WHERE post_id=?',(p['id'],))['n']; p['liked']=bool(query('SELECT user_id FROM likes WHERE post_id=? AND user_id=?',(p['id'],session['uid']))); p['comments']=query('SELECT comments.body,users.username FROM comments JOIN users ON users.id=comments.user_id WHERE comments.post_id=? ORDER BY comments.id DESC LIMIT 3',(p['id'],),many=True); posts.append(p)
    return render_template('feed.html',posts=posts)
@app.route('/create',methods=['GET','POST'])
@required
def create():
    if request.method=='POST':
        caption=request.form.get('caption','').strip(); f=request.files.get('media')
        if not caption and not (f and f.filename): flash('Write a caption or choose a photo/video.')
        elif len(caption)>2000: flash('Caption is too long.')
        else:
            try:
                filename=save_file(f,'post') if f and f.filename else ''; typ='video' if Path(filename).suffix.lower() in {'.mp4','.webm','.mov','.m4v'} else ('image' if filename else 'text')
                query('INSERT INTO posts(user_id,caption,media,media_type) VALUES(?,?,?,?)',(session['uid'],caption,filename,typ),write=True); return redirect(url_for('feed'))
            except ValueError as ex: flash(str(ex))
    return render_template('create.html')
@app.route('/like/<int:pid>',methods=['POST'])
@required
def like(pid):
    if not query('SELECT id FROM posts WHERE id=?',(pid,)): abort(404)
    if query('SELECT user_id FROM likes WHERE user_id=? AND post_id=?',(session['uid'],pid)): query('DELETE FROM likes WHERE user_id=? AND post_id=?',(session['uid'],pid),write=True)
    else:
        try: query('INSERT INTO likes(user_id,post_id) VALUES(?,?)',(session['uid'],pid),write=True)
        except Exception: pass
    return redirect(request.referrer or url_for('feed'))
@app.route('/comment/<int:pid>',methods=['POST'])
@required
def comment(pid):
    b=request.form.get('body','').strip()
    if b and len(b)<=500 and query('SELECT id FROM posts WHERE id=?',(pid,)): query('INSERT INTO comments(user_id,post_id,body) VALUES(?,?,?)',(session['uid'],pid,b),write=True)
    else: flash('Comment must be 1–500 characters.')
    return redirect(request.referrer or url_for('feed'))
@app.route('/profile',methods=['GET','POST'])
@required
def profile():
    u=me()
    if request.method=='POST':
        bio=request.form.get('bio','').strip()[:300]; f=request.files.get('avatar'); avatar=u['avatar'] or ''
        try:
            if f and f.filename: avatar=save_file(f,'avatar',True)
            query('UPDATE users SET bio=?,avatar=? WHERE id=?',(bio,avatar,u['id']),write=True); flash('Profile updated.'); return redirect(url_for('profile'))
        except ValueError as ex: flash(str(ex))
    posts=query('SELECT caption,media,media_type FROM posts WHERE user_id=? ORDER BY id DESC',(u['id'],),many=True)
    return render_template('profile.html',user=me(),posts=posts)
